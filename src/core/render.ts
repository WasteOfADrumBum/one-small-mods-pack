// Reports as terminal text, Markdown and JSON. Findings carry only masked
// evidence, so no renderer can print a secret.
import { mkdirSync, writeFileSync } from 'node:fs'
import path from 'node:path'

import type { CheckResult, Finding, GateResult } from './report'

const ICON: Record<string, string> = { PASS: 'PASS', FAIL: 'FAIL', PARTIAL: 'PARTIAL', SKIPPED: 'SKIPPED', BLOCKED: 'BLOCKED', NOT_TESTED: 'NOT TESTED' }

const where = (f: Finding) => (f.path === undefined ? '' : f.line === undefined ? f.path : `${f.path}:${f.line}`)

function findingLines(findings: readonly Finding[], limit: number): string[] {
  const order = ['critical', 'high', 'medium', 'low', 'info']
  const sorted = [...findings].sort((a, b) => order.indexOf(a.severity) - order.indexOf(b.severity))
  const shown = sorted.slice(0, limit).map(f => {
    const disposition = f.disposition === 'open' ? '' : ` [${f.disposition}: ${f.dispositionReason ?? ''}]`
    return `      ${f.severity.toUpperCase()} (${f.confidence}) ${f.rule} ${where(f)} ${f.evidence}${disposition}\n        fingerprint ${f.fingerprint}: ${f.remediation}`
  })
  if (sorted.length > limit) shown.push(`      …and ${sorted.length - limit} more (use --json or --write for all)`)
  return shown
}

export function renderText(gates: readonly GateResult[], { verbose = false } = {}): string {
  const lines: string[] = []
  for (const gate of gates) {
    lines.push(`${ICON[gate.status]} ${gate.gate}`)
    for (const check of gate.checks) {
      lines.push(`  ${ICON[check.status]} ${check.name}${check.required ? '' : ' (optional)'}: ${check.summary}`)
      for (const detail of check.details ?? []) lines.push(`      ${detail}`)
      const findings = (check.findings ?? []).filter(f => verbose || ((f.severity === 'critical' || f.severity === 'high' || f.severity === 'medium') && f.confidence !== 'possible'))
      lines.push(...findingLines(findings, verbose ? 500 : 15))
    }
  }
  return lines.join('\n')
}

const md = (text: string) => text.replace(/\|/g, '\\|').replace(/\n/g, ' ')

export function renderMarkdown(title: string, gates: readonly GateResult[], extra: string[] = []): string {
  const out: string[] = [`# ${title}`, '', `Generated by modspack on ${new Date().toISOString()}. Evidence is masked: no secret or personal value appears in this report.`, '']
  out.push('| Gate | Status |', '|---|---|', ...gates.map(g => `| ${g.gate} | ${ICON[g.status]} |`), '')
  for (const gate of gates) {
    out.push(`## ${gate.gate}: ${ICON[gate.status]}`, '')
    out.push('| Check | Status | Required | Summary |', '|---|---|---|---|')
    for (const check of gate.checks) out.push(`| ${check.name} | ${ICON[check.status]} | ${check.required ? 'yes' : 'no'} | ${md(check.summary)} |`)
    out.push('')
    for (const check of gate.checks.filter((c: CheckResult) => (c.details ?? []).length > 0)) {
      out.push(`**${check.name}**`, '', ...(check.details ?? []).map(d => `- ${d}`), '')
    }
    const findings = gate.checks.flatMap(c => c.findings ?? [])
    if (findings.length > 0) {
      out.push('| ID | Category | Severity | Confidence | Location | Evidence | Remediation | Release impact | Status |', '|---|---|---|---|---|---|---|---|---|')
      for (const f of findings) {
        const impact = f.disposition !== 'open' ? 'none (dismissed)' : f.confidence === 'possible' ? 'none (informational)' : 'see gate policy'
        out.push(`| ${f.id} | ${f.category} | ${f.severity} | ${f.confidence} | ${md(where(f))} | ${md(f.evidence)} | ${md(f.remediation)} | ${impact} | ${f.disposition}${f.dispositionReason ? `: ${md(f.dispositionReason)}` : ''} |`)
      }
      out.push('')
    }
  }
  out.push(...extra)
  return out.join('\n')
}

/** Writes `<name>.md` and `<name>.json` into the report folder and returns their paths. */
export function writeReports(projectDir: string, reportDir: string, name: string, markdown: string, json: unknown): string[] {
  const dir = path.resolve(projectDir, reportDir)
  mkdirSync(dir, { recursive: true })
  const mdPath = path.join(dir, `${name}.md`)
  const jsonPath = path.join(dir, `${name}.json`)
  writeFileSync(mdPath, markdown)
  writeFileSync(jsonPath, JSON.stringify(json, null, 2) + '\n')
  return [mdPath, jsonPath]
}
